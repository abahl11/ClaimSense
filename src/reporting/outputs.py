def markdown_table(df: pd.DataFrame, floatfmt: str | Sequence[str] = ",.2f") -> str:
    """Render a DataFrame as a GitHub markdown table without the index.

    Args:
        df: Table to render.
        floatfmt: One format for every float column, or one format per column.

    Returns:
        The markdown table.
    """
    return df.to_markdown(index=False, floatfmt=floatfmt)


def percent_columns(df: pd.DataFrame, columns: Sequence[str], decimals: int = 1) -> pd.DataFrame:
    """Return a copy with fraction columns (0-1) rendered as percentage strings."""
    out = df.copy()
    for column in columns:
        out[column] = out[column].map(lambda value: f"{value:.{decimals}%}")
    return out


def figure_markdown(image: Path, report: Path, title: str, takeaway: str) -> str:
    """Return a markdown block embedding a figure with its written takeaway.

    Args:
        image: Path of the PNG file.
        report: Path of the markdown file that will embed it (links are relative to it).
        title: Alt text and heading for the figure.
        takeaway: Two or three sentences interpreting the figure.

    Returns:
        Markdown text for the figure block.
    """
    link = Path(os.path.relpath(image, report.parent)).as_posix()
    return f"![{title}]({link})\n\n**Takeaway.** {takeaway}\n"


def write_text(text: str, path: Path) -> None:
    """Write UTF-8 text to ``path``, creating parent folders."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    logger.info("Wrote %s", path)


def _to_builtin(value: Any) -> Any:
    """Convert numpy, pandas and path objects into JSON-serialisable values."""
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        return float(value)
    if isinstance(value, np.bool_):
        return bool(value)
    if isinstance(value, pd.Timestamp):
        return value.isoformat()
    if isinstance(value, Path):
        return value.as_posix()
    raise TypeError(f"Cannot serialise {type(value).__name__} to JSON")


def write_json(data: dict[str, Any], path: Path) -> None:
    """Write a dict as indented JSON, converting numpy and pandas scalars."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, default=_to_builtin), encoding="utf-8", newline="\n")
    logger.info("Wrote %s", path)
